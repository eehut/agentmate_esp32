#!/usr/bin/env python3
"""Generate 4-bit glyph masks and UI icons. Firmware builds need no font tools.

Requires Pillow and CairoSVG. Defaults use the fonts referenced by the visual board
on macOS; explicit font paths allow regeneration elsewhere. Font files are not copied.
"""
import argparse
import hashlib
import json
import re
from io import BytesIO
from pathlib import Path

import cairosvg
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
COPY = '会话工作中思考中等待输入需要批准状态未更新任务完成任务失败任务取消剩余用量小时一周未知重置时间次日年月设备型号软件版本协议屏幕亮度灯环日期正在握手同步主机发现写入串口就绪'


def pack(pixels):
    values = [round(v / 17) for v in pixels]
    if len(values) % 2:
        values.append(0)
    return bytes((values[i] << 4) | values[i + 1] for i in range(0, len(values), 2))


def array(name, data, ctype='uint8_t'):
    digits = 4 if ctype == 'uint16_t' else 2
    return f'static const {ctype} s_{name}[] = {{\n' + ''.join(
        '    ' + ', '.join(f'0x{v:0{digits}x}' for v in data[i:i + 12]) + ',\n' for i in range(0, len(data), 12)) + '};\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    candidates = sorted(Path('/System/Library/AssetsV2/com_apple_MobileAsset_Font8').glob('*/AssetData/PingFang.ttc'))
    parser.add_argument('--cjk-font', type=Path, default=candidates[0] if candidates else None)
    parser.add_argument('--latin-font', type=Path, default=Path('/System/Library/Fonts/SFNSRounded.ttf'))
    parser.add_argument('--number-font', type=Path, default=Path('/System/Library/Fonts/HelveticaNeue.ttc'))
    args = parser.parse_args()
    if not args.cjk_font:
        parser.error('--cjk-font is required on this system')
    latin = ''.join(chr(i) for i in range(32, 127)) + '·…'
    common = sorted(set(latin + COPY))
    dynamic = set(common)
    for hi in range(0xa1, 0xf8):
        for lo in range(0xa1, 0xff):
            try:
                dynamic.add(bytes([hi, lo]).decode('gb2312'))
            except UnicodeDecodeError:
                pass
    configs = [('small', 11, common, False), ('reset', 11, common, False), ('directory_large', 14, sorted(dynamic), False),
               ('label', 13, common, False), ('identity', 15, list(latin), True), ('body', 16, common, False), ('info', 16, list(latin), False), ('date', 18, common, False),
               ('title', 19, common, True), ('state_long', 21, common, True), ('state', 23, common, True),
               ('connect', 25, common, True), ('quota', 26, list('0123456789.%?-'), True),
               ('duration_long', 22, list('0123456789:?-'), False), ('duration', 30, list('0123456789:?-'), False),
               ('clock', 45, list('0123456789:?-'), True)]
    header = ['/* Generated by tools/generate_ui_assets.py. */', '#ifndef AGENTMATE_UI_ASSETS_H', '#define AGENTMATE_UI_ASSETS_H',
              '#include <stdint.h>', '#include <stddef.h>',
              'struct am_glyph { uint32_t code, offset; uint8_t width, height, advance, top; };',
              'struct am_font { const struct am_glyph *glyphs; const uint8_t *pixels; uint16_t count; uint8_t height, scale_num, scale_den; };',
              'struct am_image { const uint8_t *mask; uint8_t width, height; };']
    license_header = (ROOT / 'main/agentmate_text.c').read_text().split('#include')[0].replace('AgentMate UTF-8 and AT text helpers', 'Generated AgentMate UI glyphs and image masks')
    license_header = license_header.replace('# 2026-10-02 1.0', '# 2026-10-03 1.1      Codex         Share cropped directory glyphs between fourteen and twelve pixel fonts.\n# 2026-10-02 1.0')
    source = [license_header, '/* Generated by tools/generate_ui_assets.py. Do not edit. */', '#include "agentmate_ui_assets.h"']
    for name, size, chars, bold in configs:
        cn = ImageFont.truetype(str(args.cjk_font), size * 3, index=11 if bold else 3)
        en = ImageFont.truetype(str(args.number_font if name.startswith('duration') else args.latin_font), size * 3,
                                index=7 if name.startswith('duration') else 0)
        if bold and not name.startswith('duration'):
            en.set_variation_by_name('Bold') if en.get_variation_names() else None
        pixels = bytearray()
        glyphs = []
        for ch in sorted(set(chars)):
            font = en if ord(ch) < 128 or ch in '·…' else cn
            advance = max(1, round(font.getlength(ch) / 3))
            if ch.isdigit() and name.startswith('duration'):
                advance = round(en.getlength('0') / 3)
            width = max(advance, (font.getbbox(ch, anchor='ls')[2] + 2) // 3)
            height = size + 4
            target_width = 8 if name == 'info' else width
            if name == 'info':
                advance = 8
            elif name == 'quota' or (name == 'reset' and ord(ch) < 128):
                target_width = max(1, round(width * 0.8))
                advance = max(1, round(advance * 0.8))
            image = Image.new('L', (width * 3, height * 3))
            ImageDraw.Draw(image).text((0, size * 3), ch, font=font, fill=255, anchor='ls')
            image = image.resize((target_width, height), Image.Resampling.LANCZOS)
            top = 0
            if name == 'directory_large':
                # Trim empty rows; top fits the existing glyph struct padding.
                bounds = image.point(lambda v: round(v / 17) * 17).getbbox()
                top = bounds[1] if bounds else 0
                bottom = bounds[3] if bounds else 1
                image = image.crop((0, top, target_width, bottom))
                height = image.height
            glyphs.append(f'    {{{ord(ch)}, {len(pixels)}, {target_width}, {height}, {advance}, {top}}},')
            pixels.extend(pack(image.get_flattened_data()))
        source += [array(name + '_pixels', pixels), f'static const struct am_glyph s_{name}_glyphs[] = {{', *glyphs, '};',
                   f'const struct am_font g_am_font_{name} = {{s_{name}_glyphs, s_{name}_pixels, {len(glyphs)}, {size + 4}, 1, 1}};']
        header.append(f'extern const struct am_font g_am_font_{name};')
        if name == 'directory_large':
            source.append(f'const struct am_font g_am_font_directory = {{s_directory_large_glyphs, s_directory_large_pixels, {len(glyphs)}, 16, 6, 7}};')
            header.append('extern const struct am_font g_am_font_directory;')
    board = (ROOT / 'docs/design/session_states_board.html').read_text()
    shapes = dict(re.findall(r"^    (\w+): '([^']+)',", board, re.M))
    # Last entry in the JS object has no trailing comma.
    shapes['lock'] = re.search(r"    lock: '([^']+)'", board)[1]
    shapes.update({
        'connected': '<path d="M11 5H9a8 8 0 0 0 0 16h2M17 5h2a8 8 0 0 1 0 16h-2M10 13h8"/>',
        'disconnected': '<path d="M10 5H9a8 8 0 0 0 0 16h1M18 5h1a8 8 0 0 1 0 16h-1m-2.5-12-3 8"/>',
    })
    for name, shape in shapes.items():
        size = 26 if name in ('connected', 'disconnected') else 38 if name in ('signal', 'link', 'sync', 'lock') else 22
        view = 28 if name in ('connected', 'disconnected') else 24
        svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {view} {view}" fill="none" stroke="#fff" stroke-width="{2.8 if view == 28 else 2.2}" stroke-linecap="round" stroke-linejoin="round">{shape.replace("currentColor", "#fff")}</svg>'
        (ROOT / f'assets/ui/{name}.svg').write_text(svg)
        image = Image.open(BytesIO(cairosvg.svg2png(bytestring=svg.encode(), output_width=size, output_height=size))).convert('RGBA')
        source += [array(name, pack(image.getchannel('A').get_flattened_data())), f'const struct am_image g_am_image_{name} = {{s_{name}, {size}, {size}}};']
        header.append(f'extern const struct am_image g_am_image_{name};')
    logo = '''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 70 70"><g transform="rotate(-15 35 35)"><rect x="8" y="8" width="54" height="54" rx="18" fill="#2e3e71" stroke="#798dff" stroke-width="2"/><circle cx="27" cy="28" r="12" fill="#36e29a"/><circle cx="44" cy="41" r="12" fill="#ff5f8d"/><circle cx="51" cy="20" r="3.5" fill="#fff"/></g></svg>'''
    (ROOT / 'assets/ui/brand.svg').write_text(logo)
    image = Image.open(BytesIO(cairosvg.svg2png(bytestring=logo.encode(), output_width=70, output_height=70))).convert('RGBA')
    bg = Image.new('RGBA', image.size, '#141733'); bg.alpha_composite(image)
    rgb = [((r & 248) << 8) | ((g & 252) << 3) | (b >> 3) for r,g,b in bg.convert('RGB').get_flattened_data()]
    source += [array('brand', rgb, 'uint16_t'), 'const uint16_t *const g_am_brand_pixels = s_brand;']
    header += ['extern const uint16_t *const g_am_brand_pixels;', '#endif']
    (ROOT / 'main/agentmate_ui_assets.h').write_text('\n'.join(header) + '\n')
    (ROOT / 'main/agentmate_ui_assets.c').write_text('\n'.join(source) + '\n')
    (ROOT / 'assets/ui/characters.txt').write_text(''.join(sorted(set(COPY))) + '\n')
    (ROOT / 'assets/ui/manifest.json').write_text(json.dumps({
        'fonts': {key: {'file': getattr(args,key).name, 'sha256': hashlib.sha256(getattr(args,key).read_bytes()).hexdigest()} for key in ('cjk_font','latin_font','number_font')},
        'directory_sizes_px': [14, 12], 'directory_shared_glyphs': True,
        'mask_bits': 4, 'dynamic_directory': 'ASCII + GB2312; unsupported glyphs use ?',
        'boot': [{'ms':0,'alpha':0}, {'ms':300,'alpha':255}, {'ms':2000,'interruptible':True}, {'ms':5000,'exit':True}],
        'status_border': {
            'bounds':[78,113,137,42], 'radius':10, 'draw_bounds':[75,110,143,48], 'fps':10,
            'period_ms':{'working':2400,'thinking':4000,'waiting_for_input':2000,'permission_required':2000,
                         'stale':3000,'task_success':4000,'task_failed':2400,'task_canceled':4000}
        },
        'led': {
            'version': 2,
            'direction': 'increasing_index',
            'disconnected_ms': [500, 3500],
            'disconnected_levels': [60, 60],
            'connecting_step_ms': 100,
            'connecting_levels': [100, 75, 40, 15],
            'permission_ms': [150, 150, 150, 1550],
            'permission_level': 55,
            'input_ms': [600, 1400],
            'input_level': 70,
            'working_step_ms': 150,
            'working_levels': [100, 100, 75, 50, 30, 15],
            'thinking_step_ms': 250,
            'thinking_levels': [80, 40, 15],
            'stale_swap_ms': 1500,
            'stale_levels': [60, 15],
            'success_stages_ms': [150, 150, 150, 750, 1200],
            'success_counts': [4, 8, 12, 16, 0],
            'success_level': 55,
            'failed_ms': [200, 2200],
            'failed_level': 55,
            'canceled_ms': [300, 2700],
            'canceled_level': 50,
            'page_dwell_ms': 10000,
        }
    }, ensure_ascii=False, indent=2) + '\n')
    print('Generated UI fonts, masks and brand')


if __name__ == '__main__':
    main()
